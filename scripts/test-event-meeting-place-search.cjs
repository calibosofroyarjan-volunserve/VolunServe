"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const ts=require("typescript");
require.extensions[".ts"]=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename);
const {searchMeetingPlaces,nearestMeetingPlace,validMeetingPlace}=require("../lib/meetingPlaceSearch.ts");
const places=require("../constants/sjdmMeetingPlaces.json");
assert(places.length>=100,"Full named-place index required; seed alone is not release-ready");
assert(places.every(validMeetingPlace),"Outside-city data");
const sti=searchMeetingPlaces(places,"STI");
assert(sti.some(p=>/sti/i.test(p.name)&&Math.abs(p.latitude-14.77916)<0.005&&Math.abs(p.longitude-121.07442)<0.005),"Verified STI landmark must be found");
const out={name:"STI fake outside city",latitude:14.5,longitude:121.0};
assert(!searchMeetingPlaces([...places,out],"STI").includes(out));
assert.equal(searchMeetingPlaces(places,"zzzzzzzzz-not-a-place").length,0);
assert.equal(nearestMeetingPlace([sti[0]],sti[0].latitude,sti[0].longitude),sti[0]);
assert.equal(nearestMeetingPlace(places,0,0),undefined);
const picker=fs.readFileSync("components/CommunityEventPinPicker.web.tsx","utf8");
for(const s of ["Use My GPS Location","Confirm Meeting Point","explicitPinRef","gpsRequestRef","nearestMeetingPlace","validVenue","draggable: true","onChange(draft.latitude, draft.longitude)"])assert(picker.includes(s),s);
const map=fs.readFileSync("components/InteractiveEventPinMap.web.tsx","utf8");
for(const s of ["draggable:true","volunserve:event-pin:ready","insideCity","sjdm-outside-shade","sjdm-outline"])assert(map.includes(s),s);
console.log("PASS named-place search, verified STI lookup, SJDM exclusion, honest nearest label and existing confirmation controls");
